/** Resolves any slug or alias to a flavour and its matched language */
export function getFlavourBySlug(rawSlug) {
  if (!rawSlug) return null;
  const clean = decodeURIComponent(rawSlug).trim().toLowerCase();

  for (const flavour of FLAVOURS) {
    if (flavour.slugs) {
      if (flavour.slugs.en.toLowerCase() === clean) return { flavour, matchedLang: 'en' };
      if (flavour.slugs.es.toLowerCase() === clean) return { flavour, matchedLang: 'es' };
      if (flavour.slugs.ca.toLowerCase() === clean) return { flavour, matchedLang: 'cat' };
    }
    if (flavour.aliases && flavour.aliases.some(a => a.toLowerCase() === clean)) {
      return { flavour, matchedLang: null };
    }
    if (flavour.id.toString() === clean) {
      return { flavour, matchedLang: null };
    }
  }
  return null;
}

/** Get canonical slug for a flavour in a given language */
export function getFlavourSlug(flavour, lang) {
  if (!flavour) return '';
  const l = lang === 'cat' ? 'ca' : (lang === 'ca' ? 'ca' : (lang === 'es' ? 'es' : 'en'));
  if (flavour.slugs && flavour.slugs[l]) {
    return flavour.slugs[l];
  }
  return flavour.slugs?.en || flavour.aliases?.[0] || `flavour-${flavour.id}`;
}

